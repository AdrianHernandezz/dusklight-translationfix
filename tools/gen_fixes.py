#!/usr/bin/env python3
"""Writes src/fixes.inc: the English text of every message this mod replaces.

Usage: python3 -I tools/gen_fixes.py <vanilla bmgres2.arc> <vanilla bmgres4.arc> \
           translationfix_1.0.0_original.zip tools/ganondorf_restoration_bmgres.arc > src/fixes.inc

Sources:
- Retranslations by ahrbro: every message translationfix 1.0.0 changed in bmgres2/4.
- Punctuation fix by ahrbro: group 4 message 5718 gets a space after "...".
- Restored cut Ganondorf dialogue by kelpoo and UltraHylia: group 0 messages 3726 and 3727,
  taken from their bmgres.arc.
"""
import os, sys, zipfile
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from bmg import yaz0, rarc, messages

def arc(data):
    return rarc(yaz0(data) if data[:4] == b'Yaz0' else data)

van = {2: open(sys.argv[1], 'rb').read(), 4: open(sys.argv[2], 'rb').read()}
z = zipfile.ZipFile(sys.argv[3])
rows = []
v4 = None
for g in (2, 4):
    name = f'zel_0{g}.bmg'
    v = dict(messages(arc(van[g])[name]))
    t = dict(messages(arc(z.read(f'overlay/res/Msgus/bmgres{g}.arc'))[name]))
    rows += [(g, k, t[k], 'ahrbro') for k in sorted(v) if v[k] != t[k]]
    if g == 4:
        v4 = v
old = v4[5718]
assert old.count(b'...and') == 1
rows.append((4, 5718, old.replace(b'...and', b'... and'), 'ahrbro'))
gd = dict(messages(arc(open(sys.argv[4], 'rb').read())['zel_00.bmg']))
rows += [(0, k, gd[k], 'kelpoo, UltraHylia') for k in (3726, 3727)]
rows.sort()

print('// Generated by tools/gen_fixes.py (English BMG text, 0-terminated).')
for g, k, raw, who in rows:
    data = ', '.join('0x%02X' % b for b in raw + b'\0')
    print('// group %d, message %d (%s)' % (g, k, who))
    print('static const uint8_t kFix_%d_%d[] = {%s};' % (g, k, data))
print('static const Fix kFixes[] = {')
for g, k, _, who in rows:
    cut = 'true' if g == 0 else 'false'  # restored cut content (Ganondorf), behind a setting
    print('    {%d, %d, kFix_%d_%d, sizeof(kFix_%d_%d), %s},' % (g, k, g, k, g, k, cut))
print('};')
