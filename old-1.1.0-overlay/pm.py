#!/usr/bin/env python3
"""Lists the English messages that name a price, for src/price_messages.inc.

Usage: python3 tools/price_messages.py bmgres1.arc ... bmgres8.arc > src/price_messages.inc

The .arc files are the game's message archives (Yaz0-compressed RARC, each holding zel_0N.bmg,
message group N). The rule for "is a price" is the same one the mod applies at runtime in
on_price_text (src/mod.cpp); keep them in step.
"""
import re
import struct
import sys

def yaz0(d):
    assert d[:4]==b'Yaz0'
    size=struct.unpack('>I',d[4:8])[0]; out=bytearray(); i=16
    while len(out)<size:
        code=d[i]; i+=1
        for b in range(8):
            if len(out)>=size: break
            if code&(0x80>>b): out.append(d[i]); i+=1
            else:
                b1,b2=d[i],d[i+1]; i+=2
                dist=((b1&0xF)<<8|b2)+1; n=b1>>4
                if n==0: n=d[i]+0x12; i+=1
                else: n+=2
                for _ in range(n): out.append(out[-dist])
    return bytes(out)
def rarc(d):
    hdr=d[:0x40]
    fdo=struct.unpack('>I',d[0xC:0x10])[0]+0x20
    info=0x20
    nodes_n,nodes_off,ent_n,ent_off,str_sz,str_off=struct.unpack('>IIIIII',d[info:info+24])
    nodes_off+=0x20; ent_off+=0x20; str_off+=0x20
    files={}
    for e in range(ent_n):
        o=ent_off+e*20
        idx,h,typ,noff,doff,sz=struct.unpack('>HHHHII',d[o:o+16])
        name=d[str_off+noff:d.index(b'\0',str_off+noff)].decode()
        if (typ>>8)&1 and name not in('.','..'):
            files[name]=d[fdo+doff:fdo+doff+sz]
    return files
def blocks(d):
    n=struct.unpack('>I',d[0xC:0x10])[0]; o=0x20; out={}
    for _ in range(n):
        tag=d[o:o+4].decode(); sz=struct.unpack('>I',d[o+4:o+8])[0]; out[tag]=o; o+=sz
    return out
def messages(d):
    b = blocks(d); inf = b['INF1']; dat = b['DAT1'] + 8
    cnt, esz = struct.unpack('>HH', d[inf + 8:inf + 12])
    res = []
    for k in range(cnt):
        e = inf + 0x10 + k * esz
        off = struct.unpack('>I', d[e:e + 4])[0]; mid = struct.unpack('>H', d[e + 4:e + 6])[0]
        j = dat + off  # text ends at a 0 byte outside a tag
        while d[j] != 0:
            j += d[j + 1] if d[j] == 0x1A else 1
        res.append((mid, d[dat + off:j]))
    return res
EXCLUDE=re.compile(rb'(\bwin|\bwon\b|prize|compensation|you got|held|hold|reward)',re.I)
def eligible(raw):
    out=[]; color=0; i=0; plain=bytearray()
    while i<len(raw):
        c=raw[i]
        if c==0x1A:
            l=raw[i+1]
            if l==6 and raw[i+2]==0xFF and raw[i+3]==0 and raw[i+4]==0: color=raw[i+5]
            i+=l; continue
        if 0x30<=c<=0x39 and not (plain and (plain[-1:].isalnum())):
            j=i
            while j<len(raw) and (0x30<=raw[j]<=0x39 or (raw[j]==0x2C and j+1<len(raw) and 0x30<=raw[j+1]<=0x39)): j+=1
            num=raw[i:j]
            # what follows, skipping tags, spaces, newlines and '-'
            k=j; follow=bytearray()
            while k<len(raw) and len(follow)<6:
                if raw[k]==0x1A: k+=raw[k+1]; continue
                if raw[k] in b' \n-' and not follow: k+=1; continue
                follow.append(raw[k]); k+=1
            rupee=bytes(follow).startswith(b'Rupee')
            if (color==6 or rupee) and b',' not in num and not EXCLUDE.search(bytes(plain[-30:])) and not (k<len(raw) and False):
                if color==6 or rupee:
                    out.append(num.decode())
            plain+=num; i=j; continue
        plain.append(c); i+=1
    return out

if __name__ == '__main__':
    rows = []
    for path in sys.argv[1:]:
        data = open(path, 'rb').read()
        if data[:4] == b'Yaz0':
            data = yaz0(data)
        for name, bmg in rarc(data).items():
            m = re.fullmatch(r'zel_0(\d)\.bmg', name)
            if not m or m.group(1) == '0':
                continue
            for mid, raw in messages(bmg):
                if eligible(raw):
                    rows.append((int(m.group(1)), mid))
    print("// Generated by tools/price_messages.py from the game's message files (bmgres1-8.arc, English):")
    print('// every message that names a price, as {message group, message ID}.')
    for grp, mid in sorted(rows):
        print('    {%d, %d},' % (grp, mid))
